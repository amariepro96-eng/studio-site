export const ICON_NAMES = Object.keys(ICONS).filter(
  (k) => !['menu', 'close', 'arrow', 'instagram', 'facebook', 'linkedin', 'tiktok', 'plus', 'minus'].includes(k)
);

export function icon(name, { size = 24, stroke = 1.75, className = '' } = {}) {
  const parts = ICONS[name] || ICONS.sparkle;
  const inner = parts
    .map((p) => {
      if (p.startsWith('c:')) {
        const [cx, cy, r] = p.slice(2).split(',');
        return `<circle cx="${cx}" cy="${cy}" r="${r}"/>`;
      }
      if (p.startsWith('r:')) {
        const [x, y, w, h, rx] = p.slice(2).split(',');
        return `<rect x="${x}" y="${y}" width="${w}" height="${h}" rx="${rx}"/>`;
      }
      return `<path d="${p}"/>`;
    })
    .join('');
  return `<svg class="ico ${className}" width="${size}" height="${size}" viewBox="0 0 24 24" fill="none" stroke="currentColor" stroke-width="${stroke}" stroke-linecap="round" stroke-linejoin="round" aria-hidden="true">${inner}</svg>`;
}

export function hasIcon(name) {
  return Object.prototype.hasOwnProperty.call(ICONS, name);
}
